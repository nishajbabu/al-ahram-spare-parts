export function isPartCompatible(part: SparePart, fitment: VehicleFitment): boolean {
  if (!fitment.make) return true;
  if (!part.compatibleMakes.includes(fitment.make)) return false;

  if (fitment.model) {
    const models = part.compatibleModels[fitment.make] || [];
    if (!models.includes(fitment.model)) return false;
  }

  if (fitment.year) {
    const yr = parseInt(fitment.year, 10);
    if (!Number.isNaN(yr) && (yr < part.yearMin || yr > part.yearMax)) {
      return false;
    }
  }

  return true;
}
